def get_system_prompt(pet_name: str, personality: dict, pet_status: dict) -> str:
    """生成系统提示词"""
    return SYSTEM_PROMPT.format(
        pet_name=pet_name,
        warmth=personality.get('warmth', 0.6),
        humor=personality.get('humor', 0.5),
        boldness=personality.get('boldness', 0.4),
        curiosity=personality.get('curiosity', 0.7),
        mood=pet_status.get('mood', 500),
        hunger=pet_status.get('hunger', 1500),
        clean=pet_status.get('clean', 1500),
        health=pet_status.get('health', 5),
    )


def get_scene_prompt(scene: str) -> str:
    """获取场景提示词"""
    return SCENE_PROMPTS.get(scene, SCENE_PROMPTS.get("click_response"))
